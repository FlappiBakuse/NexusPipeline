export function fieldLabel(key: string): string {
  if (locale.value === 'en-US') {
    const text = key.replace(/([a-z])([A-Z])/g, '$1 $2');
    return text.charAt(0).toUpperCase() + text.slice(1);
  }
  return labels[key] || key;
}
