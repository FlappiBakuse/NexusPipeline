namespace NexusPipeline.Extensibility.Lifecycle;

/// <summary>Explicit navigation, passive selectors and completion constraints for one native login.</summary>
public sealed record BrowserLoginPolicy(string Id, string StartUrl, IReadOnlyList<string> Origins, IReadOnlyList<string> PopupOrigins,
    IReadOnlyList<LoginCookieRule> Cookies, IReadOnlyList<LoginStorageRule> Storage, IReadOnlyList<LoginJsonRule> JsonRequests,
    IReadOnlyList<IReadOnlyList<string>> ReadySets, IReadOnlyList<LoginValueCheck> Checks, IReadOnlyList<IReadOnlyList<string>> EqualSets);

/// <summary>Selects one exact cookie domain, path and name.</summary>
public sealed record LoginCookieRule(string Id, string Domain, string Path, string Name);
/// <summary>Selects one storage key in its actual allowed frame origin.</summary>
public sealed record LoginStorageRule(string Id, string Origin, string Storage, string Key);
/// <summary>Observes a bounded JSON response generated by the page; never sends a credential request.</summary>
public sealed record LoginJsonRule(string Id, string Origin, string Endpoint, string Method, IReadOnlyList<string> Selector);
/// <summary>Checks nonEmpty, cookie, token, header or digits without trimming; optional storage JSON paths are literal object members.</summary>
public sealed record LoginValueCheck(string Id, string Kind, IReadOnlyList<string> Path, int MaximumLength);
