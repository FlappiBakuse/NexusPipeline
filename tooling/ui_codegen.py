"""Project the repository-owned public element ABI into frontend SDK types."""
import json
from pathlib import Path
import re


def ui_outputs(root):
    catalog = json.loads((root / "contracts/ui-elements.json").read_bytes())
    shared = json.loads((root / "contracts/ui-types.json").read_bytes())
    known = set(shared["aliases"]) | {name.split("<")[0] for name in shared["interfaces"]} | {"T"}

    def kind(text):
        primitives = {"string": "string", "boolean": "boolean", "number": "number", "null": "null", "date": "string", "HTMLElement": "HTMLElement", "File": "File"}
        if text in primitives: return primitives[text]
        if text in known: return text
        if text.startswith("Change<") and text.endswith(">"):
            return "Change<" + kind(text[7:-1]) + ">"
        if text == "HH:mm|string-empty": return "string"
        if text == "{from:date|null,to:date|null}": return "DateRange"
        if text == "readonly(file|folder)[]": return "readonly ('file' | 'folder')[]"
        if "|" in text:
            return " | ".join(kind(part) if part in primitives or part in known or part.endswith("[]") else json.dumps(part) for part in text.split("|"))
        if text.startswith("readonly ") and text.endswith("[]"):
            return "readonly " + kind(text[9:-2]) + "[]"
        if text.endswith("[]"):
            return "readonly " + kind(text[:-2]) + "[]"
        raise ValueError("Unknown public UI property type: " + text)

    def interface(name, fields, readonly=True):
        prefix = "  readonly " if readonly else "  "
        return "export interface " + name + " {\n" + "\n".join(prefix + key + ": " + kind(value) + ";" for key, value in fields.items()) + "\n}\n"

    lines = ['// <auto-generated from contracts/ui-elements.json and contracts/ui-types.json by tooling/contract_codegen.py />',
             'export const uiAbiVersion = 1 as const;']
    for name, value in shared["aliases"].items(): lines.append("export type " + name + " = " + kind(value) + ";")
    for name, value in shared["interfaces"].items(): lines.append(interface(name, value))
    names, projections, definitions, events = set(), [], {}, []
    for relative in catalog["elements"]:
        path = Path(relative)
        if path.parts[0] != "ui-elements" or len(path.parts) != 2: raise ValueError("UI definition path is not canonical")
        value = json.loads((root / "contracts" / path).read_bytes())
        name = value["name"]
        if not re.fullmatch(r"nexus-[a-z]+(?:-[a-z]+)*", name) or name in names: raise ValueError("Duplicate or unknown UI name")
        names.add(name)
        if set(value["properties"]) != set(value["defaults"]): raise ValueError("Every public UI property needs an explicit default")
        projected = "".join(part.title() for part in name.split("-")) + "Properties"
        lines.append(interface(projected, value["properties"], readonly=False))
        projections.append("  " + json.dumps(name) + ": " + projected + ";")
        definitions[name] = {key: value[key] for key in ("properties", "defaults", "slots")}
        details = ["    " + json.dumps(event) + ": " + ("MouseEvent" if detail == "native MouseEvent" else "CustomEvent<" + kind(detail) + ">") + ";"
                   for event, detail in value["events"].items()]
        events.append("  " + json.dumps(name) + ": {\n" + "\n".join(details) + "\n  };")
    if len(names) != 40: raise ValueError("Public UI registry must contain the forty retained elements")
    lines.append("export interface UiElementProperties {\n" + "\n".join(projections) + "\n}\n")
    lines.append("export type UiElementName = keyof UiElementProperties;\n")
    lines.append("export type UiElement<N extends UiElementName> = HTMLElement & UiElementProperties[N];")
    lines.append("export interface UiElementEvents {\n" + "\n".join(events) + "\n}")
    lines.append("export const uiElementDefinitions = " + json.dumps(definitions, ensure_ascii=False, indent=2) + " as const;")
    return {"sdk/frontend/src/ui-elements.generated.ts": "\n\n".join(lines) + "\n"}
