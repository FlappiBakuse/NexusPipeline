"""Generate Desktop login input limits from the authoritative Core owner."""
import argparse
from pathlib import Path
import re


def generate(root):
    source = (root / "src/core/Desktop/BrowserLoginPolicy.cs").read_text(encoding="utf-8")
    values = dict(re.findall(r"internal const int (Maximum\w+) = (\d+);", source))
    names = ("MaximumValueLength", "MaximumTotalLength", "MaximumValues", "MaximumJsonDepth")
    if set(values) != set(names):
        raise ValueError("Browser login limit declarations differ")
    return ("// Generated by tooling/browser_login_contract.py from Core BrowserValueRules.\n'use strict';\n" +
            "module.exports = Object.freeze({\n" + ",\n".join("  " + name + ": " + values[name] for name in names) + "\n});\n").encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / "apps/desktop/browser-login-limits.generated.cjs"
    expected = generate(root)
    if args.check:
        if not target.is_file() or target.read_bytes() != expected:
            raise ValueError("Desktop login limits differ from the Core owner")
    else:
        target.write_bytes(expected)


if __name__ == "__main__":
    main()
