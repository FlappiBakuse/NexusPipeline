"""Generate C#/TS message shapes from the authoritative JSON Schemas."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent


def pascal(value):
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", value))


class ProtocolGenerator:
    def __init__(self, schemas, root_documents=None):
        self.schemas = schemas
        self.root_documents = frozenset(schemas if root_documents is None else root_documents)
        self.definitions = {}
        self.typescript = {}

    def resolve(self, reference, current):
        filename, _, pointer = reference.partition("#")
        document = filename or current
        schema = self.schemas[document]
        segments = pointer.strip("/").split("/") if pointer else []
        for segment in segments:
            schema = schema[segment.replace("~1", "/").replace("~0", "~")]
        name = pascal(document.removesuffix(".schema.json"))
        if segments:
            name += pascal(segments[-1])
        return schema, document, name

    def types(self, schema, document, name):
        if not isinstance(schema, dict):
            return "JsonElement", "unknown"
        if "$ref" in schema:
            resolved, doc, resolved_name = self.resolve(schema["$ref"], document)
            return self.types(resolved, doc, resolved_name)
        if "enum" in schema and all(isinstance(v, str) for v in schema["enum"]):
            return "string", " | ".join(json.dumps(v) for v in schema["enum"])
        if "const" in schema:
            constant = schema["const"]
            return ("string" if isinstance(constant, str) else "long"), json.dumps(constant)
        kind = schema.get("type")
        if isinstance(kind, list):
            non_null = [value for value in kind if value != "null"]
            if "null" in kind and len(non_null) == 1:
                cs, ts = self.types(schema | {"type": non_null[0]}, document, name)
                return cs + "?", ts + " | null"
            return "JsonElement", "unknown"
        if kind == "object" and "properties" in schema:
            self.define(name, schema, document)
            return name, name
        if kind == "object":
            return "IReadOnlyDictionary<string, JsonElement>", "Readonly<Record<string, unknown>>"
        if kind == "array":
            cs, ts = self.types(schema.get("items", {}), document, name + "Item")
            return f"IReadOnlyList<{cs}>", f"ReadonlyArray<{ts}>"
        return {
            "string": ("string", "string"), "integer": ("long", "number"),
            "number": ("double", "number"), "boolean": ("bool", "boolean"),
        }.get(kind, ("JsonElement", "unknown"))

    def define(self, name, schema, document):
        if name in self.definitions:
            return
        self.definitions[name] = None
        required = set(schema.get("required", []))
        cs = [f'/// <summary>Wire shape from {document}; validate the schema before use.</summary>',
              "[JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]",
              f"public sealed record {name}", "{"]
        ts = [f"export interface {name} {{"]
        for key, value in schema["properties"].items():
            cs_type, ts_type = self.types(value, document, name + pascal(key))
            is_required = key in required
            cs.append(f'    /// <summary>Schema field <c>{key}</c>; constraints are owned by {document}.</summary>')
            cs.append(f'    [JsonPropertyName("{key}")]')
            if not is_required:
                cs.append("    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]")
            modifier = "required " if is_required else ""
            nullable = "" if is_required or cs_type.endswith("?") else "?"
            cs.append(f"    public {modifier}{cs_type}{nullable} {pascal(key)} {{ get; init; }}")
            ts.append(f"  readonly {key}{'' if is_required else '?'}: {ts_type};")
        cs.append("}")
        ts.append("}")
        self.definitions[name] = "\n".join(cs)
        self.typescript[name] = "\n".join(ts)

    def generate(self, namespace="NexusPipeline.Extensibility.Protocol", excluded=frozenset()):
        for document, schema in sorted(self.schemas.items()):
            if document in self.root_documents and "properties" in schema:
                self.define(pascal(document.removesuffix(".schema.json")), schema, document)
            for key, value in schema.get("$defs", {}).items():
                self.types(value, document, pascal(document.removesuffix(".schema.json")) + pascal(key))
        outputs = {}
        header = "// <auto-generated from contracts/schemas by tooling/contract_codegen.py />\n"
        directory = "sdk/dotnet/Protocol" if namespace == "NexusPipeline.Extensibility.Protocol" else "src/platform/Serialization/Protocol"
        for name, body in sorted(self.definitions.items()):
            if name in excluded:
                continue
            outputs[f"{directory}/{name}.g.cs"] = (
                header + "#nullable enable\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\n" +
                ("using NexusPipeline.Extensibility.Protocol;\n" if namespace != "NexusPipeline.Extensibility.Protocol" else "") + "\n" +
                f"namespace {namespace};\n\n" + body + "\n")
        if namespace == "NexusPipeline.Extensibility.Protocol":
            outputs["sdk/frontend/src/protocol.generated.ts"] = header + "\n\n".join(
                body for _, body in sorted(self.typescript.items())) + "\n"
        return outputs


def expected_outputs(root, shapes_only=False):
    from contract_exports import load_exports, public_schemas
    from contract_identity import compatibility, source_identity
    from ui_codegen import ui_outputs
    from web_schema import web_outputs
    schemas = {path.name: json.loads(path.read_text(encoding="utf-8"))
               for path in sorted((root / "contracts/schemas").glob("*.schema.json"))}
    exports = load_exports(root, schemas)
    selected = public_schemas(schemas, exports)
    public = ProtocolGenerator(selected, exports["pluginRoots"])
    outputs = public.generate()
    internal = ProtocolGenerator(schemas)
    outputs.update(internal.generate("NexusPipeline.Platform.Serialization.Protocol", set(public.definitions)))
    outputs.update(web_outputs(root, schemas, ProtocolGenerator))
    outputs.update(ui_outputs(root))
    for name, schema in selected.items():
        outputs["contracts/sdk-public/schemas/" + name] = json.dumps(schema, ensure_ascii=False, indent=2) + "\n"
    ui = {}
    for relative in ["ui-elements.json", "ui-types.json",
                     *json.loads((root / "contracts/ui-elements.json").read_bytes())["elements"]]:
        value = json.loads((root / "contracts" / relative).read_bytes())
        ui[relative] = value
        outputs["contracts/sdk-public/" + relative] = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
    if shapes_only:
        return outputs
    fingerprint, semantic = compatibility(root, selected, ui)
    outputs["contracts/fingerprint.json"] = json.dumps({
        "algorithm": "nexus-sdk-public-semantic-sha256-v1", "sdkVersion": "0.1.0",
        "contractFingerprint": fingerprint, "publicSchemaNames": sorted(selected),
    }, ensure_ascii=False, indent=2) + "\n"
    outputs["contracts/source-fingerprint.json"] = json.dumps(source_identity(root), ensure_ascii=False, indent=2) + "\n"
    outputs["contracts/sdk-public/fingerprint.json"] = outputs["contracts/fingerprint.json"]
    for name in ("sdk-public-api.json", "sdk-frontend-api.json"):
        outputs["contracts/sdk-public/" + name] = json.dumps(json.loads((root / "contracts" / name).read_bytes()),
                                                             ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n"
    outputs["sdk/dotnet/Protocol/SdkIdentity.g.cs"] = (
        '// <auto-generated from contracts by tooling/contract_codegen.py />\n'
        'namespace NexusPipeline.Extensibility;\n\n'
        '/// <summary>Identity of the public plugin contracts and compiled API surface.</summary>\n'
        'public static class SdkIdentity\n{\n'
        '    /// <summary>SDK package version, independent of Host and format versions.</summary>\n'
        '    public const string Version = "0.1.0";\n'
        '    /// <summary>SHA256 of the public semantic schema and compiled API description.</summary>\n'
        f'    public const string ContractFingerprint = "{fingerprint}";\n}}\n')
    outputs["sdk/frontend/src/sdk-identity.generated.ts"] = (
        '// <auto-generated from contracts by tooling/contract_codegen.py />\n'
        'export const sdkVersion = "0.1.0" as const;\n'
        f'export const contractFingerprint = "{fingerprint}" as const;\n')
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--shapes-only", action="store_true",
                        help="Prepare shapes for the first actual API-descriptor build; not a full compatibility check")
    parser.add_argument("--prune-owned", action="store_true",
                        help="Remove only obsolete byte-exact current-schema generated SDK sources")
    args = parser.parse_args()
    if args.check and (args.shapes_only or args.prune_owned):
        raise ValueError("Check cannot mutate or omit compatibility evidence")
    outputs = expected_outputs(ROOT, args.shapes_only)
    all_schemas = {path.name: json.loads(path.read_bytes()) for path in (ROOT / "contracts/schemas").glob("*.schema.json")}
    former = ProtocolGenerator(all_schemas).generate()
    unexpected = [path for path in (ROOT / "sdk/dotnet/Protocol").glob("*.g.cs")
                  if path.relative_to(ROOT).as_posix() not in outputs and
                  not (args.shapes_only and path.name == "SdkIdentity.g.cs")]
    for path in unexpected:
        relative = path.relative_to(ROOT).as_posix()
        if not args.prune_owned or relative not in former or path.read_bytes() != former[relative].encode("utf-8"):
            raise ValueError("Unowned or changed obsolete protocol source: " + relative)
        path.unlink()
    mismatches = []
    for relative, text in outputs.items():
        path = ROOT / relative
        data = text.encode("utf-8")
        if path.exists() and path.read_bytes() == data:
            continue
        if args.check:
            mismatches.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if mismatches:
        raise ValueError(f"Generated protocol shapes differ: {mismatches}")
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} protocol source files")


if __name__ == "__main__":
    main()
